// 字形の骨格を「線の通り道」として持つ。
//
// Zepp OSはフォントファイルを読み込めないので、数字は画像で用意するしかない。
// これまでは5×7のドット格子を拡大していたが、その方式では拡大率がそのまま
// ジャギーの粗さになり、8bit機の見た目から離れられない。
//
// ここでは各文字を「中心線のポリライン」として定義し、描画側が距離場から
// 太さと縁取りを起こす（tools/render-glyph.mjs）。距離は連続値なので、
// 出力サイズをいくつにしてもエッジは滑らかなまま出る。
//
// 座標系は 0..1 の正方形。x は右、y は下向き。値は「線の中心」であって
// 輪郭ではないため、太さの半分だけ内側に余裕を持たせてある。

const TAU = Math.PI * 2

// 楕円弧を折れ線へ。角度は y 下向きの標準媒介変数（0=右、π/2=下）。
// 刻みは弧長に対して十分細かく取る。距離場を作る側で滑らかになるので、
// ここでの点数は「見た目の丸み」ではなく「折れの目立たなさ」だけを決める。
function arc(cx, cy, rx, ry, from, to, steps = 40) {
  const points = []
  for (let i = 0; i <= steps; i += 1) {
    const angle = from + ((to - from) * i) / steps
    points.push([cx + rx * Math.cos(angle), cy + ry * Math.sin(angle)])
  }
  return points
}

function ellipse(cx, cy, rx, ry, steps = 56) {
  return arc(cx, cy, rx, ry, 0, TAU, steps)
}

